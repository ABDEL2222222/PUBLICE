import pandas as pd
from sklearn.linear_model import LinearRegression
import yfinance as yf

# 1. جلب بيانات الذهب لآخر شهر
gold_data = yf.download('GC=F', period='1mo', interval='1d')
if hasattr(gold_data.columns, 'levels'):
  gold_data.columns = gold_data.columns.get_level_values(0)

df = gold_data[['Close']].copy()
df.columns = ['Price']

# حساب المتوسط المتحرك البسيط لـ 3 أيام كمدخل للذكاء الاصطناعي
df['MA_3'] = df['Price'].rolling(window=3).mean()
df['Next_Day'] = df['Price'].shift(-1)
df = df.dropna()

# 2. تدريب نموذج الذكاء الاصطناعي (تعلم الآلة)
X = df[['MA_3']]
y = df['Next_Day']

model = LinearRegression()
model.fit(X, y)

# 3. توقع السعر القادم بناءً على آخر مؤشر
latest_ma = df[['MA_3']].tail(1)
predicted_price = model.predict(latest_ma)[0]
current_price = df['Price'].iloc[-1]

# طباعة النتائج
print(f'السعر الحالي: {float(current_price):.2f} دولار')
print(
    'السعر المتوقع للجلسة القادمة (بالذكاء الاصطناعي):'
    f' {float(predicted_price):.2f} دولار'
)

if predicted_price > current_price:
  print('🤖 **الذكاء الاصطناعي يتوقع:** اتجاه صاعد 📈')
else:
  print('🤖 **الذكاء الاصطناعي يتوقع:** اتجاه هابط 📉')

import pandas as pd
from sklearn.linear_model import LinearRegression
import streamlit as st
import yfinance as yf

# عنوان ومقدمة التطبيق
st.title('🪙 تطبيق تحليل أسعار الذهب بالذكاء الاصطناعي')
st.write(
    'مرحباً بك! يعرض هذا التطبيق السعر الحالي، رسماً بيانية، وتوقعاً ذكياً'
    ' للأسواق.'
)

# زر لبدء التحليل وجلب البيانات
if st.button('🔄 تحليل أسعار الذهب الآن'):
  with st.spinner('جاري جلب البيانات من البورصة وتدريب نموذج الذكاء الاصطناعي...'):

    # 1. جلب البيانات
    gold_data = yf.download('GC=F', period='2mo', interval='1d')
    if hasattr(gold_data.columns, 'levels'):
      gold_data.columns = gold_data.columns.get_level_values(0)

    current_price = float(gold_data['Close'].iloc[-1])

    # 2. عرض السعر الحالي
    st.metric(
        label='سعر أونصة الذهب الحالي (دولار)', value=f'{current_price:.2f} $'
    )

    # 3. تدريب نموذج الذكاء الاصطناعي للتنبؤ
    df = gold_data[['Close']].copy()
    df.columns = ['Price']
    df['MA_3'] = df['Price'].rolling(window=3).mean()
    df['Next_Day'] = df['Price'].shift(-1)
    df = df.dropna()

    X = df[['MA_3']]
    y = df['Next_Day']
    model = LinearRegression()
    model.fit(X, y)

    latest_ma = df[['MA_3']].tail(1)
    predicted_price = float(model.predict(latest_ma)[0])

    # عرض توقع الذكاء الاصطناعي
    st.subheader('🤖 نتيجة تحليل الذكاء الاصطناعي')
    st.write(f'السعر المتوقع للجلسة القادمة: **{predicted_price:.2f} دولار**')

    if predicted_price > current_price:
      st.success('الاتجاه المتوقع: **صاعد (إيجابي) 📈**')
    else:
      st.warning('الاتجاه المتوقع: **هابط (حذر) 📉**')

    # 4. عرض الرسم البياني
    st.subheader('📈 رسم بياني لحركة الذهب')
    st.line_chart(gold_data['Close'])

    st.success('تمت العملية بنجاح!')
else:
  st.info('👆 اضغط على الزر بالأعلى لبدء التحليل وعرض لوحة التحكم.')